interface Props {
  panelId: string;
  activeTab: WorkspaceTab | undefined;
  /** Called with `true` when the palette closes *because something was picked* (as opposed to
   * Escape/backdrop dismissal, which calls it with no argument) - callers opening this from
   * outside /workspace (see GlobalTabBar) use that distinction to navigate to /workspace only
   * once a tab actually exists to show there, not on every dismissal. */
  onClose: (opened?: boolean) => void;
}

let { panelId, activeTab, onClose }: Props = $props();

interface PaletteEntry {
  id: string;
  title: string;
  subtitle: string;
  iconClass: string;
  /** Every entry defaults to the palette's neutral icon color - only the agent entry overrides
   * this, so the one row that runs an autonomous action (instead of just opening the one tab you
   * clicked) reads as visually distinct at a glance, not identical to every resource row below it. */
  iconColorClass?: string;
  group: string;
  onSelect: () => void;
}

const containerUtils = new ContainerUtils();
const imageUtils = new ImageUtils();
const volumeUtils = new VolumeUtils();
const networkUtils = new NetworkUtils();

let query = $state('');
let selectedIndex = $state(0);

const subViewEntries = $derived.by((): PaletteEntry[] => {
  if (!activeTab) return [];
  const resourceName = activeTab.title.split(' · ')[0];
  return subViewsForResourceType(activeTab.resourceType)
    .filter(subView => subView !== activeTab.subView)
    .map(
      (subView): PaletteEntry => ({
        id: `subview-${subView}`,
        title: subViewLabel(subView),
        subtitle: `Another view of "${resourceName}"`,
        iconClass: 'fas fa-table-columns',
        group: 'This resource',
        onSelect: (): void => {
          openTab(
            {
              resourceType: activeTab.resourceType,
              resourceId: activeTab.resourceId,
              subView,
              title: `${resourceName} · ${subViewLabel(subView)}`,
            },
            'newTab',
            panelId,
          );
          onClose(true);
        },
      }),
    );
});

const podEntries = $derived(
  $podsInfos.map(
    (pod): PaletteEntry => ({
      id: `pod-${pod.id}`,
      title: pod.name,
      subtitle: 'Pod',
      iconClass: 'fas fa-cubes',
      group: 'Pods',
      onSelect: (): void => {
        openTab(
          {
            resourceType: 'pod',
            resourceId: podKey(pod.name, pod.engineId),
            subView: 'summary',
            title: `${pod.name} · Summary`,
          },
          'newTab',
          panelId,
        );
        onClose(true);
      },
    }),
  ),
);

const containerEntries = $derived(
  $containersInfos
    .map(c => containerUtils.getContainerInfoUI(c))
    .map(
      (container): PaletteEntry => ({
        id: `container-${container.id}`,
        title: container.name,
        subtitle: 'Container',
        iconClass: 'fas fa-cube',
        group: 'Containers',
        onSelect: (): void => {
          openTab(
            {
              resourceType: 'container',
              resourceId: container.id,
              subView: 'summary',
              title: `${container.name} · Summary`,
            },
            'newTab',
            panelId,
