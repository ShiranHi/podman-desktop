       detached, broken floating scrollbar. w-full (instead of a hardcoded px width) always
       matches whatever width the card actually resolves to, and overflow-hidden clips our own
       scrollable list to its rounded corners. -->
  <div class="flex flex-col w-full max-h-[70vh] rounded-xl overflow-hidden">
    <div class="p-2 border-b border-[var(--pd-content-divider)]">
      <input
        use:autofocus
        bind:value={query}
        oninput={onQueryInput}
        onkeydown={onKeydown}
        type="text"
        aria-label="Search pods, containers, images, volumes, networks, secrets, or ask the agent"
        placeholder="Search resources — or ask the agent…"
        class="w-full px-3 py-2 rounded-sm bg-[var(--pd-input-field-focused-bg)] text-[var(--pd-input-field-text)] border border-[var(--pd-input-field-focused-bg)] focus:outline-hidden" />
    </div>
    <div class="overflow-y-auto py-1">
      {#each groupedEntries as group (group.name)}
        {#if group.entries.length > 0}
          <div
            class="px-3 pt-2 pb-1 text-xs font-semibold tracking-wide text-[var(--pd-modal-dropdown-text)] opacity-70 flex items-center gap-1.5"
            class:uppercase={group.name !== AGENT_GROUP}>
            {#if group.name === AGENT_GROUP}
              <i class="fas fa-wand-magic-sparkles" aria-hidden="true"></i>
            {/if}
            {group.name}
          </div>
          {#each group.entries as entry (entry.id)}
            {@const idx = indexOfEntry(entry.id)}
            <button
              type="button"
              class="w-full flex items-center gap-3 px-3 py-2 text-left {idx === selectedIndex
                ? 'bg-[var(--pd-modal-dropdown-highlight)]'
                : 'hover:bg-[var(--pd-dropdown-bg)]'}"
              title={entry.subtitle ? `${entry.title} — ${entry.subtitle}` : entry.title}
              onmouseenter={(): void => {
                selectedIndex = idx;
              }}
              onclick={entry.onSelect}>
              <i
                class="{entry.iconClass} w-4 text-center shrink-0 {entry.iconColorClass ?? 'text-[var(--pd-modal-dropdown-text)]'}"
                aria-hidden="true"></i>
              <span class="grow overflow-hidden text-ellipsis whitespace-nowrap text-[var(--pd-modal-dropdown-text)]">
                {entry.title}
              </span>
              <span class="text-xs text-[var(--pd-modal-dropdown-text)] opacity-60 shrink-0">{entry.subtitle}</span>
            </button>
          {/each}
        {/if}
      {/each}
      {#if filteredResourceEntries.length === 0}
        <div class="px-3 py-6 text-center text-sm text-[var(--pd-modal-dropdown-text)] opacity-70">
          No matching resources — press Enter to ask the agent instead.
        </div>
      {/if}
    </div>
  </div>
</Modal>
