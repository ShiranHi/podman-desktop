const trimmedQuery = $derived(query.trim());

const AGENT_GROUP = 'Agent inspect';

// When the query's empty, lead with up to two agent findings (vuln / flaky / rebuilt).
// Typed query → single "Ask agent: …" row. Nothing found → generic prepare-layout prompt.
const proactiveInsights = $derived(findProactiveInsights(imageUIList, $podsInfos));

const agentEntries = $derived.by((): PaletteEntry[] => {
  if (trimmedQuery) {
    return [
      {
        id: 'agent',
        title: `Ask agent: "${trimmedQuery}"`,
        subtitle: 'Opens tabs automatically',
        iconClass: 'fas fa-wand-magic-sparkles',
        group: AGENT_GROUP,
        onSelect: (): void => {
          runAgentPrompt(trimmedQuery);
          onClose(true);
        },
      },
    ];
  }

  if (proactiveInsights.length > 0) {
    return proactiveInsights.map(
      (insight, index): PaletteEntry => ({
        id: `agent-insight-${index}-${insight.resourceId}`,
        title: insight.title,
        subtitle: insight.subtitle,
        iconClass: insight.iconClass,
        iconColorClass: insight.iconColorClass,
        group: AGENT_GROUP,
        onSelect: (): void => {
          openTab(
            {
              resourceType: insight.resourceType,
              resourceId: insight.resourceId,
              subView: 'summary',
              title: insight.tabTitle,
            },
            'newTab',
            panelId,
          );
          onClose(true);
        },
      }),
    );
  }

  return [
    {
      id: 'agent',
      title: 'Ask agent to prepare a layout for me',
      subtitle: 'Opens tabs automatically',
      iconClass: 'fas fa-wand-magic-sparkles',
      group: AGENT_GROUP,
      onSelect: (): void => {
        runAgentPrompt(trimmedQuery);
        onClose(true);
      },
    },
  ];
});

const filteredResourceEntries = $derived.by((): PaletteEntry[] => {
  const q = trimmedQuery.toLowerCase();
  const matches = (entry: PaletteEntry): boolean =>
    !q || entry.title.toLowerCase().includes(q) || entry.subtitle.toLowerCase().includes(q);
  return [
    ...subViewEntries,
    ...podEntries,
    ...containerEntries,
    ...imageEntries,
    ...volumeEntries,
    ...networkEntries,
    ...secretEntries,
  ].filter(matches);
});

const groupedEntries = $derived.by((): { name: string; entries: PaletteEntry[] }[] => {
  const groups: { name: string; entries: PaletteEntry[] }[] = [{ name: AGENT_GROUP, entries: agentEntries }];
  for (const entry of filteredResourceEntries) {
    let group = groups.find(g => g.name === entry.group);
    if (!group) {
      group = { name: entry.group, entries: [] };
      groups.push(group);
    }
    group.entries.push(entry);
  }
  return groups;
});

const allEntries = $derived(groupedEntries.flatMap(g => g.entries));

function onQueryInput(): void {
  selectedIndex = 0;
}

function onKeydown(event: KeyboardEvent): void {
  if (allEntries.length === 0) return;
  if (event.key === 'ArrowDown') {
    event.preventDefault();
    selectedIndex = (selectedIndex + 1) % allEntries.length;
  } else if (event.key === 'ArrowUp') {
    event.preventDefault();
    selectedIndex = (selectedIndex - 1 + allEntries.length) % allEntries.length;
  } else if (event.key === 'Enter') {
    event.preventDefault();
    allEntries[selectedIndex]?.onSelect();
  }
}

/** Every list backing this palette (pods/containers/images) comes straight from stores that
 * get a brand-new array - and brand-new entry objects - on every background poll, even when
 * nothing actually changed. Looking a row up by *object reference* (`allEntries.indexOf(entry)`)
 * would then silently return -1 the instant a poll lands between render and hover, which made
 * `selectedIndex` stick at -1 and, since every row's own index lookup failed the exact same
 * way, every row matched `-1 === -1` and lit up as "selected" at once. `id` strings are stable
 * across those refreshes, so look rows up by id instead of by identity. */
function indexOfEntry(entryId: string): number {
  return allEntries.findIndex(e => e.id === entryId);
}
