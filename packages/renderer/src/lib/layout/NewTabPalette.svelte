const secretEntries = $derived(
  $secretsInfo.map(
    (secret): PaletteEntry => ({
      id: `secret-${secret.engineId}-${secret.Id}`,
      title: secret.Name ?? '<none>',
      subtitle: 'Secret',
      iconClass: 'fas fa-key',
      group: 'Secrets',
      onSelect: (): void => {
        openTab(
          {
            resourceType: 'secret',
            resourceId: secretKey(secret.Id, secret.engineId),
            subView: 'summary',
            title: `${secret.Name ?? '<none>'} · Summary`,
          },
          'newTab',
          panelId,
        );
        onClose(true);
      },
    }),
