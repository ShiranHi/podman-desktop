        <div class="h-full flex items-center justify-center">
          <EmptyScreen
            icon="fas fa-table-cells"
            title="No tabs open"
            message="Open a container, pod, or image from its list to get started." />
        </div>
      {/snippet}
    </PanelGroup>
  </div>
