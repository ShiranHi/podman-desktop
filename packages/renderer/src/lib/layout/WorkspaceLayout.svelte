const panelCount = $derived(countTabsPanels());

function countTabsPanels(): number {
  const stack = [layoutState.tree];
  let count = 0;
  while (stack.length) {
    const node = stack.pop();
    if (!node) continue;
    if (node.kind === 'leaf') count += 1;
    else stack.push(...node.children);
  }
  return count;
}

const displayedNode = $derived.by(() => {
  if (!layoutState.maximizedPanelId) return layoutState.tree;
  const maximized = findLeaf(layoutState.tree, layoutState.maximizedPanelId);
  return maximized ?? layoutState.tree;
});

function onWindowKeydown(event: KeyboardEvent): void {
  if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase() === 'w') {
    event.preventDefault();
    closeActiveTab();
    return;
  }
  // Ctrl+Tab / Ctrl+Shift+Tab cycle through tabs in the focused panel - deliberately plain
  // Ctrl even on macOS (not Cmd+Tab), matching Cursor/VS Code's own cross-platform keybinding,
  // since Cmd+Tab is reserved by macOS itself for app-switching and would never reach the app.
  if (event.ctrlKey && event.key === 'Tab') {
    event.preventDefault();
    cycleActiveTab(event.shiftKey ? -1 : 1);
  }
}

/** Powers each panel's tab-strip "+" button: opens the new-tab command palette (other
 * sub-views of the active resource, any pod/container/image, or a free-text ask-the-agent
 * entry) scoped to that panel - see NewTabPalette.svelte. */
let newTabPaletteFor: { panelId: string; activeTab: WorkspaceTab | undefined } | undefined = $state();

function openNewTabPalette(panelId: string, activeTab: TabDescriptor | undefined): void {
  newTabPaletteFor = { panelId, activeTab: activeTab as WorkspaceTab | undefined };
}
