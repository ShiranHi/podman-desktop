// Top-level tabbed workspace: renders the current panel tree from
// layout-store.svelte.ts, and resolves each tab's content by resourceType.
// Mounted from Container/Pod/Image "workspace entry" routes - see
// ContainerWorkspaceEntry.svelte etc. Backed entirely by module-level state,
// so remounting (e.g. navigating away and back) doesn't lose anything.
