// Generated by Cursor
// The one persistent tab strip for the whole app: mounted once at the App
// root (see App.svelte), so it's visible on every page - Dashboard,
// Containers, Pods, Images, etc. - not just while inside the /workspace
// route. This is what lets a tab opened from a Pod stay reachable while
// you're browsing Images, without a dedicated "Workspace" destination to
// remember.
//
// It shows every open tab as a single flat, ordered list, regardless of
// which split/panel holds it inside the workspace - splits still exist there
// for side-by-side viewing, but from anywhere else in the app there's only
// ever one thing to reason about: "here's everything I have open".
import { TabBar } from '@podman-desktop/ui-svelte';
import { router } from 'tinro';

import {
  activeTabIdOfFocusedPanel,
  closeAllTabsEverywhere,
  closeAllTabsExcept,
  closeTabById,
  findLeafContainingTab,
  getAllTabsOrdered,
  hasEverOpenedTab,
  layoutState,
  moveToNewPanelAnyPanel,
  pinToggle,
  reorderTabGlobal,
  selectTabAnyPanel,
  splitDownAnyPanel,
  splitRightAnyPanel,
} from '/@/stores/layout/layout-store.svelte';
import type { WorkspaceTab } from '/@/stores/layout/layout-types';

import LayoutToolbar from './LayoutToolbar.svelte';
import NewTabPalette from './NewTabPalette.svelte';

let tabs = $derived(getAllTabsOrdered());
let activeTabId = $derived(activeTabIdOfFocusedPanel());
// Only ever true for the very first time this bar is empty in a fresh profile - once any tab
// has been opened, hasEverOpenedTab() flips permanently (see layout-store.svelte.ts) so this
// hint doesn't come back every time the user later closes everything.
let showFirstRunHint = $derived(tabs.length === 0 && !hasEverOpenedTab());

function onSelect(tabId: string): void {
  selectTabAnyPanel(tabId);
  router.goto('/workspace');
}

// Powers this bar's own "+" (both the inline one TabBar renders once there's at least one tab,
// and the one LayoutToolbar renders next to the gear when there are none) - same palette
// WorkspaceLayout uses per-panel, just targeting whichever panel currently has focus (or the
// one holding the active tab, so "another view of X" suggestions still make sense) since this
// bar has no panel of its own to scope to. This component is mounted on every page except
// /workspace (see App.svelte) - /workspace has its own instance per panel.
let newTabPaletteFor: { panelId: string; activeTab: WorkspaceTab | undefined } | undefined = $state();

function openNewTabPalette(): void {
  const activeTab = activeTabId ? layoutState.tabs[activeTabId] : undefined;
  const panelId =
    (activeTabId && findLeafContainingTab(layoutState.tree, activeTabId)?.id) ?? layoutState.focusedPanelId;
  newTabPaletteFor = { panelId, activeTab };
}

function closeNewTabPalette(opened?: boolean): void {
  newTabPaletteFor = undefined;
  // A pick from here always lands the new tab inside /workspace's panel tree - without this,
  // it'd open successfully but stay invisible until the user happened to navigate there
  // themselves. Escape/backdrop dismissal (opened is undefined) stays right where it was.
  if (opened) router.goto('/workspace');
}
</script>

{#snippet firstRunHint()}
  <i class="fas fa-table-cells opacity-70" aria-hidden="true"></i>
  <span class="ml-2">Open a container, pod, or image to start a tab here - or use Layout options to load a preset</span>
{/snippet}

<!-- Always rendered - even with zero tabs open - so the Layout settings button in `trailing`
     stays reachable as the entry point for starting a layout in the first place (new layout,
     a built-in preset, importing one, or the agent demo). -->
<TabBar
  panelId="global-tab-bar"
  {tabs}
  {activeTabId}
  {onSelect}
  onClose={closeTabById}
  onCloseOthers={closeAllTabsExcept}
  onCloseAllInPanel={closeAllTabsEverywhere}
  onPinToggle={(tabId): void => pinToggle('global-tab-bar', tabId)}
  onReorder={reorderTabGlobal}
  onMoveFromOtherPanel={(_sourcePanelId, tabId, beforeTabId): void => reorderTabGlobal(tabId, beforeTabId)}
  onSplitRight={splitRightAnyPanel}
  onSplitDown={splitDownAnyPanel}
  onMoveToNewPanel={moveToNewPanelAnyPanel}
  onAddTab={openNewTabPalette}
  emptyHint={showFirstRunHint ? firstRunHint : undefined}>
  {#snippet trailing()}
    <LayoutToolbar onAddTab={openNewTabPalette} />
  {/snippet}
</TabBar>

{#if newTabPaletteFor}
  <NewTabPalette
    panelId={newTabPaletteFor.panelId}
    activeTab={newTabPaletteFor.activeTab}
    onClose={closeNewTabPalette} />
{/if}
