// Generated by Cursor
// Svelte action for the first field of every layout-feature modal (Save Layout As, the preset
// pickers, the new-tab command palette) - focuses it as soon as it's mounted so users can start
// typing/selecting immediately instead of having to click into the field themselves first, the
// same way Cmd+P/Ctrl+P-style palettes and "New folder" dialogs behave in most editors.
export function autofocus(node: HTMLElement): void {
  node.focus();
  if (node instanceof HTMLInputElement && node.type !== 'file' && node.type !== 'checkbox') {
    node.select();
  }
}
