function compareResourceLabels(aName: string, aStatus: string, bName: string, bStatus: string): number {
  const nameCmp = aName.localeCompare(bName, undefined, { sensitivity: 'base', numeric: true });
  const statusCmp = aStatus.localeCompare(bStatus, undefined, { sensitivity: 'base' });
  switch (resourceSort) {
    case 'name-desc':
      return -nameCmp || statusCmp;
    case 'status-asc':
      return statusCmp || nameCmp;
    case 'status-desc':
      return -statusCmp || nameCmp;
    case 'name-asc':
    default:
      return nameCmp || statusCmp;
  }
}

function sortResources<T>(items: T[], nameOf: (item: T) => string, statusOf: (item: T) => string): T[] {
  return items.toSorted((a, b) => compareResourceLabels(nameOf(a), statusOf(a), nameOf(b), statusOf(b)));
}

