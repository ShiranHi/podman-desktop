    rememberAppPage('/', 'Dashboard');
    router.goto('/');
  } else if (id === 'extensions') {
    rememberAppPage('/extensions', 'Extensions');
    router.goto('/extensions');
  } else if (id === 'settings') {
    router.goto('/preferences/resources');
  } else {
    rememberAppPage('/containers', 'Containers');
    router.goto('/containers');
  }
}

