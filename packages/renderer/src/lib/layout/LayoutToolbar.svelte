// Generated by Cursor
// A single settings-gear button - meant to be dropped into a tab bar's
// `trailing` slot (see TabBar.svelte) rather than occupying its own full-width
// row - that opens the "Layout" menu: quick actions (close all tabs, save the
// current one, jump to a preset) up front, with everything about *managing*
// saved layouts (the full list, export/import, the agent demo) tucked behind
// a single "Manage Layouts…" entry instead of turning this into a mile-long list.
import { faFloppyDisk, faFolderOpen, faGear, faXmark } from '@fortawesome/free-solid-svg-icons';
import { Button, DropdownMenu } from '@podman-desktop/ui-svelte';
import { Icon } from '@podman-desktop/ui-svelte/icons';

import Dialog from '/@/lib/dialogs/Dialog.svelte';
import { saveNamedLayout } from '/@/stores/layout/layout-persistence.svelte';
import { type PresetId, PRESETS } from '/@/stores/layout/layout-presets';
import { closeAllTabsEverywhere, hasAnyTabs } from '/@/stores/layout/layout-store.svelte';

import { autofocus } from './autofocus';
import ManageLayoutsModal from './ManageLayoutsModal.svelte';
import PresetPickerModal from './PresetPickerModal.svelte';

let showMenu = $state(false);
let menuAnchor = $state<HTMLButtonElement>();
let menuEl = $state<HTMLDivElement>();
let clientX = $state(0);
let clientY = $state(0);
// Hidden (off-screen + invisible) until positionMenu() below has measured the menu's real size
// and placed it - avoids a one-frame flash at the top-left corner.
let menuStyle = $state('top: -9999px; left: -9999px; visibility: hidden;');

let showSaveDialog = $state(false);
let saveName = $state('');
let activePreset: PresetId | undefined = $state();
let showManageModal = $state(false);

// Closing the "Save Layout As" dialog was previously the only feedback a successful save gave -
// the saved name only ever showed up later, inside "Manage Layouts…", if you went looking for
// it. A brief self-dismissing toast confirms the save actually happened, right where it happened.
let saveToastMessage: string | undefined = $state();
let saveToastTimeout: ReturnType<typeof setTimeout> | undefined;

function toggleMenu(event: MouseEvent): void {
  const rect = (event.currentTarget as HTMLElement).getBoundingClientRect();
  clientX = rect.left;
  clientY = rect.bottom;
  showMenu = !showMenu;
  if (showMenu) {
    // Reset to hidden before the effect below re-measures and re-places the (freshly mounted)
    // menu - otherwise it would flash at wherever it was left positioned last time it was open.
    menuStyle = 'top: -9999px; left: -9999px; visibility: hidden;';
  }
}

// This menu is embedded in each panel's tab bar (see the `trailing` slot wiring in
// WorkspaceLayout/GlobalTabBar), and Panel.svelte's own root clips overflow (so a split's
// content can't spill into its neighbor). A plain `position: absolute` dropdown - anchored to
// its small parent wrapper, as the shared DropdownMenu.Items component does - gets clipped at
// that panel boundary instead of floating over it (the "menu got cut" bug). Positioning this
// one with `position: fixed` and explicit viewport coordinates (computed here, once the menu's
// real size is known) escapes that clipping entirely, the same way the app's modals do.
$effect(() => {
  if (!showMenu || !menuEl) return;
  const rect = menuEl.getBoundingClientRect();
  const margin = 8;

  let top = clientY + margin;
  if (top + rect.height > window.innerHeight - margin) {
    // Flip to open upward from the button instead of down, roughly undoing the button's own
    // height (~32px) plus the same gap so it doesn't overlap the button itself.
    top = Math.max(margin, clientY - rect.height - 40);
  }

  let left = clientX;
  if (left + rect.width > window.innerWidth - margin) {
    left = Math.max(margin, window.innerWidth - rect.width - margin);
  }

  menuStyle = `top: ${top}px; left: ${left}px; visibility: visible;`;
});

function handleEscape({ key }: KeyboardEvent): void {
  if (key === 'Escape') showMenu = false;
}

function onWindowClick(e: MouseEvent): void {
  const target = e.target;
  if (target instanceof Node && (menuAnchor?.contains(target) || menuEl?.contains(target))) return;
  showMenu = false;
}

function closeAllTabsAction(): void {
  showMenu = false;
  if (!hasAnyTabs()) return;
  closeAllTabsEverywhere();
}

function openSaveDialog(): void {
  showMenu = false;
  if (!hasAnyTabs()) return;
  saveName = '';
  showSaveDialog = true;
}

function confirmSave(): void {
  const name = saveName.trim();
  if (!name) return;
  saveNamedLayout(name);
  showSaveDialog = false;

  saveToastMessage = `Saved as "${name}"`;
  clearTimeout(saveToastTimeout);
  saveToastTimeout = setTimeout(() => {
    saveToastMessage = undefined;
  }, 3000);
}

function pickPreset(id: PresetId): void {
  showMenu = false;
  activePreset = id;
}

function openManageModal(): void {
  showMenu = false;
  showManageModal = true;
}
</script>

<svelte:window onkeyup={handleEscape} onclick={onWindowClick} />

<div class="relative flex items-stretch text-left">
  <button
    bind:this={menuAnchor}
    type="button"
    aria-label="Layout options"
    title="Layout options"
    aria-haspopup="menu"
    aria-expanded={showMenu}
    class="flex items-center px-2.5 hover:bg-[var(--pd-action-button-details-bg)] text-[var(--pd-tab-text)]"
    onclick={toggleMenu}>
    <Icon class="w-4 text-sm" icon={faGear} />
  </button>

  {#if showMenu}
    <div
      bind:this={menuEl}
      role="menu"
      tabindex="-1"
      style={menuStyle}
      class="fixed z-50 w-64 max-h-[80vh] overflow-y-auto rounded-md shadow-lg bg-[var(--pd-dropdown-bg)] ring-2 ring-[var(--pd-dropdown-ring)] hover:ring-[var(--pd-dropdown-hover-ring)] divide-y divide-[var(--pd-dropdown-divider)] focus:outline-hidden">
      <DropdownMenu.Item title="Close All Tabs" icon={faXmark} enabled={hasAnyTabs()} onClick={closeAllTabsAction} />
      <DropdownMenu.Item
        title="Save Layout As…"
        icon={faFloppyDisk}
        enabled={hasAnyTabs()}
        tooltip={hasAnyTabs() ? undefined : 'Nothing to save - open a tab first'}
        onClick={openSaveDialog} />
      <DropdownMenu.Item title="Manage Layouts…" icon={faFolderOpen} onClick={openManageModal} />

      <div>
        <div class="px-3 pt-2 pb-1 text-xs font-semibold uppercase tracking-wide text-[var(--pd-dropdown-item-text)] opacity-60">
          Presets
        </div>
        {#each PRESETS as preset (preset.id)}
          <DropdownMenu.Item
            title={preset.title}
            tooltip={preset.description}
            icon={preset.iconClass}
            onClick={(): void => pickPreset(preset.id)} />
        {/each}
      </div>
    </div>
  {/if}
</div>

{#if showSaveDialog}
  <Dialog
    title="Save Layout As"
    onclose={(): void => {
      showSaveDialog = false;
    }}>
    {#snippet content()}
      <div class="w-full">
        <label for="layoutName" class="block my-2 text-sm font-bold text-[var(--pd-modal-text)]">Layout name</label>
        <input
          id="layoutName"
          use:autofocus
          class="w-full p-2 rounded-sm bg-[var(--pd-input-field-focused-bg)] text-[var(--pd-input-field-text)]"
          placeholder="e.g. Nightly debug session"
          bind:value={saveName}
          onkeydown={(e: KeyboardEvent): void => {
            if (e.key === 'Enter') confirmSave();
          }} />
      </div>
    {/snippet}
    {#snippet buttons()}
      <Button
        type="link"
        on:click={(): void => {
          showSaveDialog = false;
        }}>Cancel</Button>
      <Button type="primary" disabled={!saveName.trim()} on:click={confirmSave}>Save</Button>
    {/snippet}
  </Dialog>
{/if}

{#if activePreset}
  <PresetPickerModal presetId={activePreset} onClose={(): void => (activePreset = undefined)} />
{/if}

{#if showManageModal}
  <ManageLayoutsModal
    onClose={(): void => {
      showManageModal = false;
    }} />
{/if}

{#if saveToastMessage}
  <div
    role="status"
    class="fixed bottom-4 right-4 z-50 flex items-center gap-2 px-3 py-2 rounded-md shadow-lg bg-[var(--pd-dropdown-bg)] ring-2 ring-[var(--pd-dropdown-ring)] text-sm text-[var(--pd-dropdown-item-text)]">
    <i class="fas fa-circle-check text-[var(--pd-status-running)]" aria-hidden="true"></i>
    {saveToastMessage}
  </div>
{/if}
