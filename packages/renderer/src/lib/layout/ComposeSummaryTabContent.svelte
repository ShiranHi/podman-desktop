<script lang="ts">
// Generated by Cursor
// Carded Compose summary (header + overview + containers), matching Pod/Container tabs.
import { Link, StatusIcon } from '@podman-desktop/ui-svelte';

import ComposeDetailsInspect from '/@/lib/compose/ComposeDetailsInspect.svelte';
import type { ComposeInfoUI } from '/@/lib/compose/ComposeInfoUI';
import type { ContainerInfoUI } from '/@/lib/container/ContainerInfoUI';
import PodIcon from '/@/lib/images/PodIcon.svelte';
import { composeKey } from '/@/stores/layout/layout-types';

import { openContainerInWorkspace } from './resource-open-actions';
import EnvironmentField from './summary/EnvironmentField.svelte';
import InspectCard from './summary/InspectCard.svelte';
import OverviewField from './summary/OverviewField.svelte';
import ResourceSummaryHeader from './summary/ResourceSummaryHeader.svelte';
import SummaryCard from './summary/SummaryCard.svelte';

interface Props {
  tabId: string;
  compose: ComposeInfoUI;
}

let { tabId, compose }: Props = $props();

const runningCount = $derived(compose.containers.filter(c => c.state.toUpperCase() === 'RUNNING').length);
const stoppedCount = $derived(compose.containers.length - runningCount);

const allPorts = $derived(
  compose.containers.flatMap(c =>
    (c.ports ?? []).map(port => ({
      port,
      containerName: c.name,
    })),
  ),
);

function openContainer(container: ContainerInfoUI): void {
  openContainerInWorkspace({ id: container.id, name: container.name }, 'newTab');
}
</script>

<div class="flex flex-col gap-4 px-5 py-4">
  <ResourceSummaryHeader
    name={compose.name}
    status={compose.status}
    statusLabel={compose.status.toLowerCase()}
    icon={PodIcon}
    id={compose.engineId} />

  <SummaryCard title="Overview" icon="fas fa-table-list">
    <div class="grid grid-cols-2 sm:grid-cols-3 gap-3 px-4 pb-3">
      <OverviewField label="Status" value={compose.status.toLowerCase()} />
      <EnvironmentField engineId={compose.engineId} />
      <OverviewField label="Engine type" value={compose.engineType} />
      <OverviewField
        label="Containers"
        value="{compose.containers.length} ({runningCount} running · {stoppedCount} stopped)" />
    </div>
  </SummaryCard>

  <SummaryCard title="Containers" icon="fas fa-cubes">
    {#snippet trailing()}
      {runningCount} running · {stoppedCount} stopped
    {/snippet}
    {#if compose.containers.length > 0}
      <div class="divide-y divide-[var(--pd-content-divider)]">
        {#each compose.containers as container (container.id)}
          <div class="flex items-center gap-3 px-4 py-2.5">
            <StatusIcon status={container.state.toUpperCase()} size={14} />
            <div class="flex flex-col min-w-0 flex-1 gap-0.5">
              <Link on:click={(): void => openContainer(container)}>{container.name}</Link>
              <span class="text-xs text-[var(--pd-content-text)] opacity-60 truncate">
                {container.image || 'No image'} · {container.shortId || container.id.substring(0, 12)}
              </span>
            </div>
            <span class="text-xs text-[var(--pd-content-text)] opacity-70 lowercase shrink-0">{container.state}</span>
          </div>
        {/each}
      </div>
    {:else}
      <div class="px-4 pb-3 text-sm text-[var(--pd-content-text)] opacity-60">No containers</div>
    {/if}
  </SummaryCard>

  {#if allPorts.length > 0}
    <SummaryCard title="Network" icon="fas fa-network-wired">
      <div class="divide-y divide-[var(--pd-content-divider)]">
        {#each allPorts as { port, containerName }, i (`${containerName}-${port.PrivatePort}-${port.Type}-${i}`)}
          <div class="flex items-center justify-between px-4 py-2 text-sm">
            <span class="text-[var(--pd-content-text)] opacity-80">{containerName}</span>
            <span class="font-mono text-xs text-[var(--pd-content-header)]">
              {port.IP || '0.0.0.0'}:{port.PublicPort} → {port.PrivatePort}/{port.Type}
            </span>
          </div>
        {/each}
      </div>
    </SummaryCard>
  {/if}

  <InspectCard
    resourceType="compose"
    resourceId={composeKey(compose.name, compose.engineId)}
    resourceTitle={compose.name}
    {tabId}>
    <ComposeDetailsInspect compose={compose} />
  </InspectCard>
</div>
