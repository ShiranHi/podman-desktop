interface Props {
  podName: string;
  engineId: string;
}

let { podName, engineId }: Props = $props();

let pod = $derived($podsInfos.find(p => p.name === podName && p.engineId === engineId));

$effect(() => {
  if (!pod) return;
  const item = pod;
  untrack(() => {
    const requested = $router.path.split('/').filter(Boolean).at(-1);
    const subView = (
      ['summary', 'logs', 'inspect', 'kube'].includes(requested ?? '') ? requested : 'summary'
    ) as PodSubView;
    openTab(
      {
        resourceType: 'pod',
        resourceId: podKey(item.name, item.engineId),
        subView,
        title: `${item.name} · ${subView[0].toUpperCase() + subView.slice(1)}`,
      },
      'replace',
    );
    router.goto('/workspace');
  });
});
