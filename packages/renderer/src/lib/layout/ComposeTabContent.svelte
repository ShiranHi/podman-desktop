<script lang="ts">
// Generated by Cursor
// Compose group sub-views inside a workspace tab (Summary/Logs/Inspect/Kube).
import ComposeDetailsInspect from '/@/lib/compose/ComposeDetailsInspect.svelte';
import ComposeDetailsKube from '/@/lib/compose/ComposeDetailsKube.svelte';
import ComposeDetailsLogs from '/@/lib/compose/ComposeDetailsLogs.svelte';
import type { ComposeInfoUI } from '/@/lib/compose/ComposeInfoUI';
import { ContainerUtils } from '/@/lib/container/container-utils';
import { containersInfos } from '/@/stores/containers';
import { markTabStale } from '/@/stores/layout/layout-store.svelte';
import type { ComposeSubView } from '/@/stores/layout/layout-types';

import ComposeSummaryTabContent from './ComposeSummaryTabContent.svelte';
import StaleTabPlaceholder from './StaleTabPlaceholder.svelte';

interface Props {
  tabId: string;
  composeName: string;
  engineId: string;
  subView?: ComposeSubView;
}

let { tabId, composeName, engineId, subView = 'summary' }: Props = $props();

const containerUtils = new ContainerUtils();

let compose = $derived.by((): ComposeInfoUI | undefined => {
  const containersMatchingProject = $containersInfos.filter(
    container => container?.Labels?.['com.docker.compose.project'] === composeName,
  );
  if (containersMatchingProject.length === 0) {
    return undefined;
  }
  const allRunning = containersMatchingProject.every(container => container?.State === 'running');
  const convertedContainers = containersMatchingProject.map(container => containerUtils.getContainerInfoUI(container));
  return {
    name: composeName,
    engineId,
    engineType: convertedContainers[0]?.engineType ?? 'podman',
    status: allRunning ? 'RUNNING' : 'STOPPED',
    containers: convertedContainers,
  };
});

$effect(() => {
  markTabStale(tabId, !compose);
});
</script>

{#if compose}
  <div class="flex flex-col h-full min-h-0">
    <div class="grow min-h-0 overflow-auto">
      {#if subView === 'inspect'}
        <ComposeDetailsInspect compose={compose} />
      {:else if subView === 'kube'}
        <ComposeDetailsKube compose={compose} />
      {:else if subView === 'logs'}
        <ComposeDetailsLogs compose={compose} />
      {:else}
        <ComposeSummaryTabContent {tabId} compose={compose} />
      {/if}
    </div>
  </div>
{:else}
  <StaleTabPlaceholder resourceLabel="Compose" tabId={tabId} />
{/if}
