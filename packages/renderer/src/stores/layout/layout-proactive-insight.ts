// Generated by Cursor
// What the "+" tab palette's Agent inspect rows lead with when the user hasn't typed
// anything yet. Scans mock metrics (vulnerabilities, restarts, rebuild age) and surfaces
// up to two findings so the empty-query palette itself is a useful action.
import type { ImageInfoUI } from '/@/lib/image/ImageInfoUI';
import type { PodInfoUI } from '/@/lib/pod/PodInfoUI';

import { imageKey, podKey } from './layout-types';
import {
  formatVulnBreakdown,
  getImageMockMetrics,
  getImageUpdateInfo,
  getPodMockMetrics,
} from './mock-resource-metrics';

export interface ProactiveInsight {
  title: string;
  subtitle: string;
  iconClass: string;
  iconColorClass: string;
  resourceType: 'image' | 'pod';
  resourceId: string;
  tabTitle: string;
}

const MAX_INSIGHTS = 2;

/** Collect findings in priority order (security → reliability → version bump), return up to
 * {@link MAX_INSIGHTS} distinct resources so the palette can show more than one agent tip. */
export function findProactiveInsights(images: ImageInfoUI[], pods: PodInfoUI[]): ProactiveInsight[] {
  const insights: ProactiveInsight[] = [];
  const usedResourceIds = new Set<string>();

  function push(insight: ProactiveInsight): void {
    if (insights.length >= MAX_INSIGHTS) return;
    if (usedResourceIds.has(insight.resourceId)) return;
    usedResourceIds.add(insight.resourceId);
    insights.push(insight);
  }

  const vulnerableImages = images
    .map(image => {
      const id = imageKey(image.id, image.engineId, image.base64RepoTag);
      const metrics = getImageMockMetrics(id);
      const severity = metrics.critical * 10 + metrics.high;
      return { image, id, severity, metrics };
    })
    .filter(row => row.severity > 0)
    .sort((a, b) => b.severity - a.severity);

  for (const row of vulnerableImages) {
    const label = `${row.image.name}:${row.image.tag}`;
    push({
      title: `${label} has ${formatVulnBreakdown(row.metrics)}`,
      subtitle: 'Agent found this - open it',
      iconClass: 'fas fa-triangle-exclamation',
      iconColorClass: 'text-[var(--pd-status-degraded)]',
      resourceType: 'image',
      resourceId: row.id,
      tabTitle: `${label} · Summary`,
    });
  }

  const flakyPods = pods
    .map(pod => {
      const { restarts } = getPodMockMetrics(podKey(pod.name, pod.engineId));
      return { pod, restarts };
    })
    .filter(row => row.restarts >= 2)
    .sort((a, b) => b.restarts - a.restarts);

  for (const row of flakyPods) {
    push({
      title: `${row.pod.name} restarted ${row.restarts} times`,
      subtitle: 'Agent found this - open it',
      iconClass: 'fas fa-arrow-rotate-right',
      iconColorClass: 'text-[var(--pd-status-degraded)]',
      resourceType: 'pod',
      resourceId: podKey(row.pod.name, row.pod.engineId),
      tabTitle: `${row.pod.name} · Summary`,
    });
  }

  for (const image of images) {
    const id = imageKey(image.id, image.engineId, image.base64RepoTag);
    const { updateAvailable, daysAgo } = getImageUpdateInfo(id);
    if (!updateAvailable) continue;
    const label = `${image.name}:${image.tag}`;
    push({
      title: `${label} was rebuilt ${daysAgo}d ago`,
      subtitle: 'Agent found a newer version - open it',
      iconClass: 'fas fa-rotate',
      iconColorClass: 'text-[var(--pd-status-running)]',
      resourceType: 'image',
      resourceId: id,
      tabTitle: `${label} · Summary`,
    });
  }

  return insights;
}

/** @deprecated Prefer {@link findProactiveInsights}; kept for single-insight callers. */
export function findProactiveInsight(images: ImageInfoUI[], pods: PodInfoUI[]): ProactiveInsight | undefined {
  return findProactiveInsights(images, pods)[0];
}
