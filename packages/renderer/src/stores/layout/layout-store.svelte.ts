// The Tabs & Flexible Layout prototype's central state: a tree of panels
// (splits) each holding an ordered list of tabs, plus the tab registry
// itself. Lives in a plain module-level `$state` (same pattern as
// `tablePersistence` in @podman-desktop/ui-svelte) so it survives component
// remounts as the user navigates between routes.
import type { LeafPanelNode, OpenMode, PanelNode, SplitDirection, SplitPanelNode } from '@podman-desktop/ui-svelte';
import { router } from 'tinro';

import { goBack, navigationHistory } from '/@/stores/navigation-history.svelte';

import type { SubView, WorkspaceResourceType, WorkspaceTab } from './layout-types';
import { tabKey, workspaceTabIcon, workspaceTabNavigationIcon } from './layout-types';
import { getPageTabIcon, getPageTabTitle, PAGE_TAB_ID } from './page-tab.svelte';

// Tracks the current route so closing the last tab can tell whether the user is
// actually looking at /workspace right now (see closeTabInternal below) - closing a
// tab from the global bar while browsing e.g. Pods shouldn't yank the user anywhere,
// since they're already on the page they want.
let currentRouteUrl = $state('/');
router.subscribe(route => {
  currentRouteUrl = route.url;
});

export interface OpenTabInput {
  resourceType: WorkspaceResourceType;
  resourceId: string;
  subView?: SubView;
  title: string;
  subtitle?: string;
  iconClass?: string;
}

let idCounter = 0;
function genId(prefix: string): string {
  idCounter += 1;
  return `${prefix}-${Date.now().toString(36)}-${idCounter}`;
}

function createLeaf(): LeafPanelNode {
  return { kind: 'leaf', id: genId('panel'), tabIds: [], activeTabId: undefined };
}

const initialLeaf = createLeaf();

interface LayoutState {
  tree: PanelNode;
  tabs: Record<string, WorkspaceTab>;
  focusedPanelId: string;
  maximizedPanelId: string | undefined;
}

export const layoutState: LayoutState = $state({
  tree: initialLeaf,
  tabs: {},
  focusedPanelId: initialLeaf.id,
  maximizedPanelId: undefined,
});

// ---- pure tree lookups (read-only traversal; mutations happen on the caller's captured references since layoutState.tree is deeply reactive) ----

export function findLeaf(node: PanelNode, id: string): LeafPanelNode | undefined {
  if (node.kind === 'leaf') return node.id === id ? node : undefined;
  for (const child of node.children) {
    const found = findLeaf(child, id);
    if (found) return found;
  }
  return undefined;
}

export function findLeafContainingTab(node: PanelNode, tabId: string): LeafPanelNode | undefined {
  if (node.kind === 'leaf') return node.tabIds.includes(tabId) ? node : undefined;
  for (const child of node.children) {
    const found = findLeafContainingTab(child, tabId);
    if (found) return found;
  }
  return undefined;
}

export function findFirstLeaf(node: PanelNode): LeafPanelNode {
  return node.kind === 'leaf' ? node : findFirstLeaf(node.children[0]);
}

export function findLastLeaf(node: PanelNode): LeafPanelNode {
  return node.kind === 'leaf' ? node : findLastLeaf(node.children[node.children.length - 1]);
}

function findParent(node: PanelNode, childId: string): SplitPanelNode | undefined {
  if (node.kind === 'leaf') return undefined;
  for (const child of node.children) {
    if (child.id === childId) return node;
    const found = findParent(child, childId);
    if (found) return found;
  }
  return undefined;
}

export function countLeaves(node: PanelNode): number {
  return node.kind === 'leaf' ? 1 : node.children.reduce((sum, child) => sum + countLeaves(child), 0);
}

export function getTabsForPanel(panelId: string): WorkspaceTab[] {
  const leaf = findLeaf(layoutState.tree, panelId);
  if (!leaf) return [];
  return leaf.tabIds.map(id => layoutState.tabs[id]).filter((t): t is WorkspaceTab => !!t);
}

export function findExistingTabByKey(key: string): WorkspaceTab | undefined {
  return Object.values(layoutState.tabs).find(t => t.key === key);
}

/** Any open tab (regardless of subView) pointing at this resource - used to avoid stomping on a tab the user already has open on a different sub-view. */
export function findAnyTabForResource(
  resourceType: WorkspaceTab['resourceType'],
  resourceId: string,
): WorkspaceTab | undefined {
  return Object.values(layoutState.tabs).find(t => t.resourceType === resourceType && t.resourceId === resourceId);
}

// ---- mutation helpers ----

function removeTabFromLeaf(leaf: LeafPanelNode, tabId: string): void {
  const idx = leaf.tabIds.indexOf(tabId);
  if (idx === -1) return;
  leaf.tabIds.splice(idx, 1);
  if (leaf.activeTabId === tabId) {
    leaf.activeTabId = leaf.tabIds[Math.max(0, idx - 1)] ?? leaf.tabIds[0];
  }
}

/** Keep the current app page as the first, permanent tab in the first section. */
export function ensurePageTab(): void {
  const title = getPageTabTitle();
  const existing = layoutState.tabs[PAGE_TAB_ID];
  if (!existing) {
    layoutState.tabs[PAGE_TAB_ID] = {
      id: PAGE_TAB_ID,
      key: PAGE_TAB_ID,
      title,
      permanent: true,
      pinned: true,
      resourceType: 'app-page',
      resourceId: 'app-page',
      iconClass: 'fas fa-house',
      tabIcon: getPageTabIcon(),
    };
  } else {
    existing.title = title;
    existing.tabIcon = getPageTabIcon();
    existing.permanent = true;
    existing.pinned = true;
  }

  const home = findFirstLeaf(layoutState.tree);
  function removeFromOtherLeaves(node: PanelNode): void {
    if (node.kind === 'leaf') {
      if (node.id !== home.id) removeTabFromLeaf(node, PAGE_TAB_ID);
      return;
    }
    node.children.forEach(removeFromOtherLeaves);
  }
  removeFromOtherLeaves(layoutState.tree);

  const index = home.tabIds.indexOf(PAGE_TAB_ID);
  if (index === -1) home.tabIds.unshift(PAGE_TAB_ID);
  else if (index > 0) {
    home.tabIds.splice(index, 1);
    home.tabIds.unshift(PAGE_TAB_ID);
  }
  if (!home.activeTabId || !home.tabIds.includes(home.activeTabId)) home.activeTabId = PAGE_TAB_ID;
}

/** Select the permanent page tab while keeping the user in the workspace. */
export function activatePageTab(): void {
  ensurePageTab();
  const home = findFirstLeaf(layoutState.tree);
  home.activeTabId = PAGE_TAB_ID;
  layoutState.focusedPanelId = home.id;
}

export function resourceTabCount(): number {
  return Object.keys(layoutState.tabs).filter(id => id !== PAGE_TAB_ID).length;
}

/** Removes an empty leaf from the tree, collapsing its parent split if it drops to a single remaining child. */
function pruneEmptyLeaf(leafId: string): void {
  if (layoutState.tree.kind === 'leaf') return; // never prune the last remaining panel
  const parent = findParent(layoutState.tree, leafId);
  if (!parent) return;
  const idx = parent.children.findIndex(c => c.id === leafId);
  if (idx === -1) return;
  parent.children.splice(idx, 1);
  parent.sizes.splice(idx, 1);

  if (layoutState.maximizedPanelId === leafId) layoutState.maximizedPanelId = undefined;
  if (layoutState.focusedPanelId === leafId) {
    layoutState.focusedPanelId = findFirstLeaf(layoutState.tree).id;
  }

  if (parent.children.length === 1) {
    const onlyChild = parent.children[0];
    const grandParent = findParent(layoutState.tree, parent.id);
    if (grandParent) {
      const parentIdx = grandParent.children.findIndex(c => c.id === parent.id);
      grandParent.children[parentIdx] = onlyChild;
    } else {
      layoutState.tree = onlyChild;
    }
  }
}

function closeTabInternal(panelId: string, tabId: string): void {
  if (layoutState.tabs[tabId]?.permanent || tabId === PAGE_TAB_ID) return;
  const leaf = findLeaf(layoutState.tree, panelId);
  if (!leaf) return;
  removeTabFromLeaf(leaf, tabId);
  delete layoutState.tabs[tabId];
  if (leaf.tabIds.length === 0) pruneEmptyLeaf(leaf.id);

  if (resourceTabCount() === 0) activatePageTab();

  // Match VS Code/Cursor: closing the very last open tab leaves nothing for
  // /workspace to show, so send the user back to whatever page they were on
  // before they started opening tabs - browser-style "back", not a dead end.
  // Only applies while /workspace is actually on screen; closing a tab via the
  // global bar from e.g. the Pods list should just drop it from the bar and
  // leave the user right where they already are.
  if (Object.keys(layoutState.tabs).length === 0 && currentRouteUrl.startsWith('/workspace')) {
    if (navigationHistory.index > 0) {
      goBack();
    } else {
      router.goto('/');
    }
  }
}

/** Wraps `targetLeafId` in a new split (if needed) with a fresh sibling leaf, and returns that new leaf. */
function splitLeaf(targetLeafId: string, direction: SplitDirection, position: 'before' | 'after'): LeafPanelNode {
  const newLeaf = createLeaf();
  const parent = findParent(layoutState.tree, targetLeafId);

  if (parent?.direction === direction) {
    const idx = parent.children.findIndex(c => c.id === targetLeafId);
    const insertAt = position === 'after' ? idx + 1 : idx;
    parent.children.splice(insertAt, 0, newLeaf);
    const avg = parent.sizes[idx] ?? 100 / parent.children.length;
    parent.sizes.splice(insertAt, 0, avg);
    return newLeaf;
  }

  // need a brand-new split wrapping the target leaf
  const targetNode = parent ? parent.children[parent.children.findIndex(c => c.id === targetLeafId)] : layoutState.tree;
  const newSplit: SplitPanelNode = {
    kind: 'split',
    id: genId('split'),
    direction,
    children: position === 'after' ? [targetNode, newLeaf] : [newLeaf, targetNode],
    sizes: [50, 50],
  };

  if (parent) {
    const idx = parent.children.findIndex(c => c.id === targetLeafId);
    parent.children[idx] = newSplit;
  } else {
    layoutState.tree = newSplit;
  }
  return newLeaf;
}

